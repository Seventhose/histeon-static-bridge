#!/usr/bin/env python3
"""English translation files from Italian sources (docs/spec/i18n.md).

The plugins are written in Italian. The translations live in JSON maps (Italian -> English, one or more files in a
folder), easy to review and to split; this script turns them into what WordPress loads:

  i18n.py po <file.pot> <maps-dir> <out.po> [--strict]
      Writes the .po (every msgid of the .pot with its English text) and the .mo next to it, and a Jed JSON file
      for each JavaScript file the .pot names (wp_set_script_translations). Lists what has no translation;
      --strict fails on it.

  i18n.py check <maps-dir> <file.php|file.js>...
      The gettext literals of the files (approximate, by pattern) that the maps do not translate yet: for checking
      a part while translating, before the .pot exists.

Only the standard library: no gettext tools needed.
"""
import hashlib
import json
import os
import re
import struct
import sys
from pathlib import Path

LANG = 'en_US'
PLURAL = 'nplurals=2; plural=(n != 1);'


def load_maps(folder):
    out = {}
    for path in sorted(Path(folder).glob('*.json')):
        data = json.loads(path.read_text('utf8'))
        if not isinstance(data, dict):
            raise SystemExit(f'{path}: not an object')
        for k, v in data.items():
            if not isinstance(k, str) or not isinstance(v, str):
                raise SystemExit(f'{path}: {k!r} is not text')
            out[k] = v
    return out


def unquote(s):
    s = s[1:-1]
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t', 'r': '\r', '"': '"', '\\': '\\'}.get(m.group(1), '\\' + m.group(1)), s)


def quote(s):
    s = s.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t').replace('\r', '\\r')
    if '\n' in s and s != '\n':
        lines = s.split('\n')
        parts = [line + '\\n' for line in lines[:-1]] + ([lines[-1]] if lines[-1] else [])
        return '""\n' + '\n'.join(f'"{p}"' for p in parts)
    return '"' + s.replace('\n', '\\n') + '"'


def parse_pot(path):
    entries, cur, field = [], None, None
    def flush():
        if cur and 'msgid' in cur:
            entries.append(cur)
    for raw in Path(path).read_text('utf8').splitlines() + ['']:
        line = raw.strip()
        if not line:
            flush()
            cur, field = None, None
            continue
        if cur is None:
            cur = {'comments': [], 'refs': []}
        if line.startswith('#:'):
            cur['refs'] += line[2:].split()
        elif line.startswith('#'):
            cur['comments'].append(raw)
        else:
            m = re.match(r'(msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?)\s+(".*")$', line)
            if m:
                field = m.group(1)
                cur[field] = unquote(m.group(2))
            elif line.startswith('"') and field:
                cur[field] += unquote(line)
    return entries


def translate(entry, maps):
    msgid = entry['msgid']
    if 'msgid_plural' in entry:
        one, many = maps.get(msgid), maps.get(entry['msgid_plural'])
        return [one, many] if one is not None and many is not None else None
    text = maps.get(msgid)
    return None if text is None else [text]


def write_mo(path, messages):
    keys = sorted(messages)
    ids = b''
    strs = b''
    offsets = []
    for k in keys:
        kb, vb = k.encode('utf8'), messages[k].encode('utf8')
        offsets.append((len(ids), len(kb), len(strs), len(vb)))
        ids += kb + b'\0'
        strs += vb + b'\0'
    n = len(keys)
    start = 7 * 4 + n * 16
    # No hash table, but its address right after the two tables, as GNU msgfmt writes it: WordPress's classic MO
    # reader (and tools built on it) checks that the tables end where the hash table starts.
    out = struct.pack('<7I', 0x950412de, 0, n, 7 * 4, 7 * 4 + n * 8, 0, start)
    out += b''.join(struct.pack('<2I', length, start + o) for o, length, _, _ in offsets)
    out += b''.join(struct.pack('<2I', length, start + len(ids) + o) for _, _, o, length in offsets)
    Path(path).write_bytes(out + ids + strs)


def header(domain):
    return (f'Project-Id-Version: {domain}\nMIME-Version: 1.0\nContent-Type: text/plain; charset=UTF-8\n'
            f'Content-Transfer-Encoding: 8bit\nLanguage: {LANG}\nPlural-Forms: {PLURAL}\nX-Domain: {domain}\n')


def cmd_po(pot, folder, out, strict):
    maps = load_maps(folder)
    entries = [e for e in parse_pot(pot) if e['msgid'] != '']
    domain = re.sub(r'-' + LANG + r'$', '', Path(out).stem)
    if domain == LANG:
        # A theme's file is <locale>.po: the domain is the one the .pot names.
        found = re.search(r'"X-Domain: ([^"\\]+)\\n"', Path(pot).read_text('utf8'))
        domain = found.group(1) if found else domain
    po = ['# English translation (docs/spec/i18n.md). Generated by scripts/i18n.py from the maps: edit those.',
          'msgid ""', 'msgstr ""'] + [f'"{line}\\n"' for line in header(domain).rstrip('\n').split('\n')] + ['']
    mo = {'': header(domain)}
    scripts = {}
    missing = []
    for e in entries:
        text = translate(e, maps)
        if text is None:
            missing.append(e['msgid'])
        po += e['comments'] + ([f"#: {' '.join(e['refs'])}"] if e['refs'] else [])
        if 'msgctxt' in e:
            po.append('msgctxt ' + quote(e['msgctxt']))
        po.append('msgid ' + quote(e['msgid']))
        key = (e['msgctxt'] + '\x04' if 'msgctxt' in e else '') + e['msgid']
        if 'msgid_plural' in e:
            po.append('msgid_plural ' + quote(e['msgid_plural']))
            values = text or ['', '']
            po += [f'msgstr[{i}] ' + quote(v) for i, v in enumerate(values)]
            if text:
                mo[key + '\0' + e['msgid_plural']] = '\0'.join(text)
        else:
            po.append('msgstr ' + quote(text[0] if text else ''))
            if text:
                mo[key] = text[0]
        po.append('')
        if text:
            for ref in e['refs']:
                file = ref.rsplit(':', 1)[0]
                if file.endswith('.js'):
                    scripts.setdefault(file, {})[key] = text
    Path(out).write_text('\n'.join(po), 'utf8')
    write_mo(Path(out).with_suffix('.mo'), mo)
    for file, messages in scripts.items():
        # WordPress looks for <domain>-<locale>-<md5 of the script path relative to the plugin>.json.
        name = f"{domain}-{LANG}-{hashlib.md5(file.encode('utf8')).hexdigest()}.json"
        messages = {'': {'domain': 'messages', 'lang': LANG, 'plural-forms': PLURAL}, **messages}
        Path(out).with_name(name).write_text(json.dumps({'domain': 'messages', 'locale_data': {'messages': messages}}, ensure_ascii=False, separators=(',', ':')), 'utf8')
    print(f'{len(entries) - len(missing)}/{len(entries)} translated, {len(scripts)} script files', file=sys.stderr)
    for m in missing:
        print('  missing: ' + m.replace('\n', '\\n'), file=sys.stderr)
    return 1 if strict and missing else 0


PHP_CALL = re.compile(r"\b(?:__|_e|_x|_ex|_n|_nx|_n_noop|esc_html__|esc_html_e|esc_attr__|esc_attr_e|esc_html_x|esc_attr_x)\(\s*"
                      r"('(?:\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\")(?:\s*,\s*('(?:\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\"))?")


def php_literal(s):
    body = s[1:-1]
    if s[0] == "'":
        return re.sub(r"\\(['\\])", r'\1', body)
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t', '"': '"', '\\': '\\', '$': '$'}.get(m.group(1), '\\' + m.group(1)), body)


def cmd_check(folder, files):
    maps = load_maps(folder)
    missing = []
    for file in files:
        source = Path(file).read_text('utf8')
        for m in PHP_CALL.finditer(source):
            name = source[m.start():source.index('(', m.start())]
            texts = [m.group(1)] + ([m.group(2)] if name in ('_n', '_nx', '_n_noop') and m.group(2) else [])
            for lit in texts:
                text = php_literal(lit)
                if text not in maps:
                    missing.append(f'{file}: {text}')
    for line in missing:
        print(line)
    print(f'{len(missing)} missing', file=sys.stderr)
    return 1 if missing else 0


def main(argv):
    if len(argv) >= 5 and argv[1] == 'po':
        return cmd_po(argv[2], argv[3], argv[4], '--strict' in argv)
    if len(argv) >= 3 and argv[1] == 'check':
        return cmd_check(argv[2], argv[3:])
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv))
